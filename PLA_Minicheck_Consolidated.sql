SELECT 'RowStore Size'             AS CHECK_NAME,
       'ALL-' || TO_NVARCHAR(ROUND(SUM(ALLOCATED_SIZE) / 1073741824, 3)) ||
       ',USE-' || TO_NVARCHAR(ROUND(SUM(USED_SIZE)      / 1073741824, 3))    AS RESULT
FROM SYS.M_RS_MEMORY
UNION ALL
SELECT 'ColumnStore Size',
       TO_NVARCHAR(ROUND(SUM(MEMORY_SIZE_IN_TOTAL) / 1073741824, 3))
FROM SYS.M_CS_TABLES
UNION ALL
SELECT 'Indexserver Memory',
       'ALL:' || TO_NVARCHAR(ROUND(SUM(ALLOCATION_LIMIT)       / 1073741824, 3)) ||
       ',USE:' || TO_NVARCHAR(ROUND(SUM(TOTAL_MEMORY_USED_SIZE) / 1073741824, 3))
FROM SYS.M_SERVICE_MEMORY WHERE SERVICE_NAME = 'indexserver'
UNION ALL
SELECT 'Plan Cache HIT Ratio (40d)',
       TO_NVARCHAR(ROUND(AVG(PLAN_CACHE_HIT_RATIO), 6))
FROM _SYS_STATISTICS.HOST_SQL_PLAN_CACHE_OVERVIEW
WHERE SERVER_TIMESTAMP >= ADD_DAYS(CURRENT_TIMESTAMP, -40)
UNION ALL
SELECT 'High Memory Allocators B4P >30pct',
       TO_NVARCHAR(COUNT(*))
FROM SYS.M_HEAP_MEMORY H
JOIN SYS.M_SERVICES S ON H.HOST = S.HOST AND H.PORT = S.PORT
WHERE S.SERVICE_NAME = 'indexserver'
  AND H.INCLUSIVE_SIZE_IN_USE * 100.0 /
      NULLIF((SELECT SUM(ALLOCATION_LIMIT) FROM SYS.M_SERVICE_MEMORY
              WHERE SERVICE_NAME = 'indexserver'), 0) > 30
UNION ALL
SELECT 'Top 10 Allocators B4P',
       STRING_AGG(HOST || '|' || SERVICE_NAME || '|' || CATEGORY || '|'
                  || TO_NVARCHAR(ROUND(INCLUSIVE_SIZE_IN_USE / 1073741824, 3)) || 'GB'
                  || '|' || TO_NVARCHAR(ROUND(EXCLUSIVE_SIZE_IN_USE / 1073741824, 3)) || 'GB',
                  '; ' ORDER BY INCLUSIVE_SIZE_IN_USE DESC)
FROM (
    SELECT TOP 10 H.HOST, S.SERVICE_NAME, H.CATEGORY,
           H.INCLUSIVE_SIZE_IN_USE, H.EXCLUSIVE_SIZE_IN_USE
    FROM SYS.M_HEAP_MEMORY H
    JOIN SYS.M_SERVICES    S ON H.HOST = S.HOST AND H.PORT = S.PORT
    WHERE S.SERVICE_NAME = 'indexserver'
    ORDER BY H.INCLUSIVE_SIZE_IN_USE DESC
) T
UNION ALL
SELECT 'OOM Events B4P (40d)',
