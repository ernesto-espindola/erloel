FROM (
    SELECT COUNT(*) AS NUM_EVENTS, ALERT_RATING, ALERT_ID,
           MAX(ALERT_DETAILS) AS ALERT_DETAILS
    FROM _SYS_STATISTICS.STATISTICS_ALERTS_BASE
    WHERE ALERT_RATING = 5
